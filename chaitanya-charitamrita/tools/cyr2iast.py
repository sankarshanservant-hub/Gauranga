# Кириллическая транслитерация ВЧД (с диакритикой) -> IAST (латиница), обратная к tools/cyr.py.
# Транслитерация уже сверена с изданием Гаудия Матха, поэтому английское издание берёт её отсюда, а не с vedabase.
import re, unicodedata
M = [('джж', 'jj'), ('джх', 'jh'), ('дж', 'j'), ('чх', 'ch'), ('т̣х', 'ṭh'), ('д̣х', 'ḍh'), ('р̣̄', 'ṝ'), ('кх', 'kh'), ('гх', 'gh'),
     ('тх', 'th'), ('дх', 'dh'), ('пх', 'ph'), ('бх', 'bh'), ('а̄', 'ā'), ('ӣ', 'ī'), ('ӯ', 'ū'), ('р̣', 'ṛ'), ('л̣', 'ḷ'),
     ('н̇', 'ṅ'), ('н̃', 'ñ'), ('т̣', 'ṭ'), ('д̣', 'ḍ'), ('н̣', 'ṇ'), ('ш́', 'ś'), ('ш̣', 'ṣ'), ('м̇', 'ṁ'), ('х̣', 'ḥ'),
     ('аи', 'ai'), ('ау', 'au'), ('э', 'e'), ('а', 'a'), ('и', 'i'), ('у', 'u'), ('е', 'e'), ('о', 'o'), ('к', 'k'), ('г', 'g'),
     ('ч', 'c'), ('т', 't'), ('д', 'd'), ('н', 'n'), ('п', 'p'), ('б', 'b'), ('м', 'm'), ('й', 'y'), ('р', 'r'), ('л', 'l'),
     ('в', 'v'), ('с', 's'), ('х', 'h')]
def conv(s):
    s = unicodedata.normalize('NFC', s)
    out, i = '', 0
    while i < len(s):
        if s[i] == '̐':                       # чандрабинду над гласной: та̄̐ха̄ -> tāṅhā (как принято в IAST изданий ЧЧ)
            out += 'ṅ'; i += 1; continue
        for a, b in M:
            if s.startswith(a, i):
                out += b; i += len(a); break
        else:
            out += s[i]; i += 1
    return out
if __name__ == '__main__':
    import sys
    for l in sys.stdin: print(conv(l.rstrip('\n')))
